"""Render the per-language verdict tables (appendix of an audit report) from the harness JSON."""
import json, sys, collections
T = json.load(open(sys.argv[1])); S = json.load(open(sys.argv[2])); out = sys.argv[3]
LIVE_SERVERS = {'python/corpus.py': 'Pylance', 'config/corpus.toml': 'Even Better TOML'}
key = lambda x: (x['file'], x['component'])
Sm = {key(x): x for x in S if not x.get('summary') and not x.get('error')}
def cell(o, ex):
    if o['v'] == 'EXACT': return 'EXACT'
    s = f"{o['v']}: {o['actual']}"
    return s + (' (mixed)' if o.get('mixed') else '')
by = collections.defaultdict(list)
for x in T:
    if x.get('summary') or x.get('error'): continue
    by[x['file']].append(x)
L = ['# A1 appendix: verdicts per component', '', 'Generated by `audit/harness/tables.py` from `A1-T.json` and `A1-S.json`. '
     'Expected role is the Role Map entry; `?Qn` marks an entry waiting on design question n. Hex is Sea Salt.', '']
for f, rows in by.items():
    modes = []
    for x in rows:
        for m in Sm.get(key(x), {'modes': {}})['modes']:
            if m != 'T' and m not in modes and (m != 'S-servers' or f in LIVE_SERVERS): modes.append(m)
    names = ['T'] + [('S ' + LIVE_SERVERS[f]) if m == 'S-servers' else m.replace('S-', 'S ') for m in modes]
    L += [f'## {f}', '', '| Component | Token | Expected | ' + ' | '.join(names) + ' |', '|---|---|---|' + '---|' * len(names)]
    for x in rows:
        ex = x['expect']; exs = ex['role'] + (f"?{ex['question']}" if ex['question'] else '') + (f" (T may: {ex['fallbackT']})" if ex['fallbackT'] else '')
        cells = [cell(x['modes']['T'], ex) + f" `{x['modes']['T']['fg']}`"]
        s = Sm.get(key(x))
        for m in modes:
            o = s['modes'].get(m) if s else None
            cells.append(cell(o, ex) + f" `{o['fg']}`" if o else '-')
        tok = x['token'].lstrip('~').rsplit('#', 1)[0] if '#' in x['token'][1:] else x['token'].lstrip('~')
        L.append(f"| `{x['component']}` | `{tok.replace('|', '¦')}` | {exs} | " + ' | '.join(c.replace('|', '¦') for c in cells) + ' |')
    L.append('')
open(out, 'w', encoding='utf-8').write('\n'.join(L))
c = collections.Counter(x['modes']['T']['v'] for r in by.values() for x in r)
print('rows', sum(len(r) for r in by.values()), dict(c))
